export function getRootPortfolioProjects() {
  return portfolioProjects.filter((project) => !project.parentId);
}

export function getPortfolioProjectsByParent(parentId) {
  return portfolioProjects.filter((project) => project.parentId === parentId);
}

export function getPortfolioProjectById(id) {
  return portfolioProjects.find((project) => project.id === id);
}
